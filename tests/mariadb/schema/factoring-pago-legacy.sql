CREATE TABLE `factoring_pago` (
  `_idfactoringpago` int(11) unsigned NOT NULL AUTO_INCREMENT,
  `factoringpagoid` varchar(50) NOT NULL DEFAULT uuid(),
  `code` varchar(255) NOT NULL,
  `_idfactoring` int(11) unsigned NOT NULL,
  `_idempresacuentabancaria` int(11) unsigned NOT NULL,
  `_idfactorcuentabancaria` int(11) unsigned NOT NULL,
  `numero_operacion` varchar(50) NOT NULL,
  `fecha_pago` timestamp NOT NULL,
  `monto_pagado` decimal(10,2) NOT NULL,
  `idusuariocrea` int(11) NOT NULL DEFAULT 1,
  `fechacrea` timestamp(3) NOT NULL DEFAULT current_timestamp(3),
  `idusuariomod` int(11) NOT NULL DEFAULT 1,
  `fechamod` timestamp(3) NOT NULL DEFAULT current_timestamp(3),
  `estado` tinyint(4) NOT NULL DEFAULT 1,
  PRIMARY KEY (`_idfactoringpago`),
  UNIQUE KEY `UQ_factoringpago_factoringpagoid` (`factoringpagoid`),
  UNIQUE KEY `UQ_factoringpago_code` (`code`),
  KEY `_idaceptante` (`_idfactoring`) USING BTREE,
  KEY `_idcedente` (`_idfactorcuentabancaria`) USING BTREE,
  KEY `_idmoneda` (`_idempresacuentabancaria`) USING BTREE,
  CONSTRAINT `FK_factoring_pago_empresa_cuenta_bancaria` FOREIGN KEY (`_idempresacuentabancaria`) REFERENCES `empresa_cuenta_bancaria` (`_idempresacuentabancaria`),
  CONSTRAINT `FK_factoring_pago_factor_cuenta_bancaria` FOREIGN KEY (`_idfactorcuentabancaria`) REFERENCES `factor_cuenta_bancaria` (`_idfactorcuentabancaria`),
  CONSTRAINT `FK_factoring_pago_factoring` FOREIGN KEY (`_idfactoring`) REFERENCES `factoring` (`_idfactoring`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
